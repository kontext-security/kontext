package stepsafety

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"testing"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"
	"golang.org/x/text/unicode/rangetable"
)

// The table must come from HF's Unicode 9.0 view, not from whichever Unicode
// version the Go toolchain selects: go1.27 moves x/text from 15.0 to 17.0
// tables, which add reorderings and compositions HF does not know.
func TestPostUnicode9TableCoversXText(t *testing.T) {
	unicode9 := rangetable.Assigned("9.0.0")
	current := rangetable.Assigned(norm.Version)
	if current == nil {
		t.Fatalf("x/text has no assigned table for Unicode %s", norm.Version)
	}
	var want []rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !utf8.ValidRune(r) || unicode.Is(unicode9, r) {
			continue
		}
		p := norm.NFC.PropertiesString(string(r))
		if !p.BoundaryBefore() || !p.BoundaryAfter() || norm.NFD.PropertiesString(string(r)).Decomposition() != nil {
			want = append(want, r)
		}
	}
	newer := false
	rangetable.Visit(postUnicode9NFC, func(r rune) {
		switch {
		case unicode.Is(unicode9, r):
			t.Errorf("U+%04X is in Unicode 9.0, so HF normalizes it", r)
		case !unicode.Is(current, r):
			newer = true
		case !slices.Contains(want, r):
			t.Errorf("U+%04X is inert under Unicode %s", r, norm.Version)
		}
	})
	// Regenerating on an older toolchain would drop the newer runes.
	if os.Getenv("UPDATE_GOLDEN") == "1" && !newer {
		writePostUnicode9Table(t, want)
		return
	}
	for _, r := range want {
		if !unicode.Is(postUnicode9NFC, r) {
			t.Errorf("U+%04X normalizes under Unicode %s but is missing from postUnicode9NFC; regenerate with UPDATE_GOLDEN=1 go test -run %s", r, norm.Version, t.Name())
		}
	}
}

func writePostUnicode9Table(t *testing.T, runes []rune) {
	t.Helper()
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by UPDATE_GOLDEN=1 go test -run %s; DO NOT EDIT.\n\n", t.Name())
	b.WriteString("package stepsafety\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "// postUnicode9NFC holds the runes Unicode 9.0 leaves unassigned that the\n// Unicode %s normalization tables reorder, compose or decompose.\n", norm.Version)
	b.WriteString("var postUnicode9NFC = &unicode.RangeTable{\n")
	// Consecutive runs only, so each range can be checked against the UCD.
	section := ""
	for i := 0; i < len(runes); {
		j := i
		for j+1 < len(runes) && runes[j+1] == runes[j]+1 {
			j++
		}
		want := "R16: []unicode.Range16"
		if runes[j] > 0xffff {
			want = "R32: []unicode.Range32"
		}
		if want != section {
			if section != "" {
				b.WriteString("},\n")
			}
			section = want
			b.WriteString(section + "{\n")
		}
		fmt.Fprintf(&b, "{Lo: 0x%04x, Hi: 0x%04x, Stride: 1},\n", runes[i], runes[j])
		i = j + 1
	}
	b.WriteString("},\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("unicode9.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}
