#!/usr/bin/env bash
# Renders Casks/kontext.rb for kontext-security/homebrew-tap.
#
# A cask installs the prebuilt, notarized binary as is. Unlike the formula,
# which has no bottle, Homebrew does not treat it as a source build, so it
# never runs its Xcode and Command Line Tools checks. Only publish it for
# releases whose macOS binaries are notarized: casks keep the quarantine
# attribute, and Gatekeeper blocks an un-notarized binary.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <checksums-file>" >&2
  exit 1
fi

version="$1"
checksums_file="$2"

if [[ ! -f "$checksums_file" ]]; then
  echo "checksums file not found: $checksums_file" >&2
  exit 1
fi

sha_for() {
  local archive="kontext_${version}_$1.tar.gz"
  local sha

  sha="$(awk -v archive="$archive" '$2 == archive { print $1; exit }' "$checksums_file")"
  if [[ -z "$sha" ]]; then
    echo "missing checksum for $archive" >&2
    exit 1
  fi

  printf '%s\n' "$sha"
}

darwin_arm64_sha="$(sha_for darwin_arm64)"
darwin_amd64_sha="$(sha_for darwin_amd64)"
linux_arm64_sha="$(sha_for linux_arm64)"
linux_amd64_sha="$(sha_for linux_amd64)"
base_url="https://github.com/kontext-security/kontext/releases/download/v#{version}"

cat <<EOF
# This file was generated by the Kontext release workflow. DO NOT EDIT.
cask "kontext" do
  version "${version}"

  on_macos do
    on_arm do
      url "${base_url}/kontext_#{version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64_sha}"
    end
    on_intel do
      url "${base_url}/kontext_#{version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64_sha}"
    end
  end
  on_linux do
    on_arm do
      url "${base_url}/kontext_#{version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64_sha}"
    end
    on_intel do
      url "${base_url}/kontext_#{version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64_sha}"
    end
  end

  name "Kontext"
  desc "Identity, credentials, and governance for AI agents"
  homepage "https://kontext.security"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "kontext"
end
EOF
